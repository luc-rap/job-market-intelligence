SELECT $1
FROM @JOB_MARKET_INTELLIGENCE.RAW.ADZUNA_STAGE_TEMP
LIMIT 5;


CREATE TABLE IF NOT EXISTS JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS (
    RAW_DATA VARIANT,
    SOURCE_FILE VARCHAR,
    LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);


COPY INTO JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS
    (RAW_DATA, SOURCE_FILE)
FROM (
    SELECT
        $1,
        METADATA$FILENAME
    FROM @JOB_MARKET_INTELLIGENCE.RAW.ADZUNA_STAGE_TEMP
)
FILE_FORMAT = (
    FORMAT_NAME = 'JOB_MARKET_INTELLIGENCE.RAW.ADZUNA_JSON_FORMAT'
)
ON_ERROR = 'ABORT_STATEMENT';

SELECT
    COUNT(*) AS DOCUMENT_COUNT,
    COUNT(DISTINCT SOURCE_FILE) AS FILE_COUNT,
    MIN(LOADED_AT) AS FIRST_LOADED_AT,
    MAX(LOADED_AT) AS LAST_LOADED_AT
FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS;

SELECT *
FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS

SELECT
    TYPEOF(RAW_DATA) AS DATA_TYPE,
    ARRAY_SIZE(RAW_DATA) AS JOBS_IN_DOCUMENT,
    RAW_DATA[0] AS FIRST_JOB,
    SOURCE_FILE
FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS
LIMIT 1;

SELECT
    f.INDEX AS JOB_POSITION,
    f.VALUE:adref::VARCHAR AS ADREF,
    f.VALUE:title::VARCHAR AS JOB_TITLE,
    f.VALUE:company.display_name::VARCHAR AS COMPANY_NAME,
    f.VALUE:location.display_name::VARCHAR AS LOCATION,
    r.SOURCE_FILE
FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS r,
LATERAL FLATTEN(INPUT => r.RAW_DATA) f
ORDER BY r.SOURCE_FILE, f.INDEX;