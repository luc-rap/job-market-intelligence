USE ROLE ACCOUNTADMIN;

-- Table the root task writes to, which is what consumes the stream
CREATE TABLE IF NOT EXISTS JOB_MARKET_INTELLIGENCE.RAW.RAW_LOAD_LOG (
  CHECKED_AT TIMESTAMP_NTZ,
  NEW_ROWS   NUMBER
);

-- Stream that watches your raw table
CREATE OR REPLACE STREAM JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS_STREAM
  ON TABLE JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS
  APPEND_ONLY = TRUE;

-- Should return FALSE right now, since nothing has loaded since the stream was created
SELECT SYSTEM$STREAM_HAS_DATA('JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS_STREAM');

USE ROLE ACCOUNTADMIN;

-- Root task: fires when new rows land, and consumes the stream
CREATE OR ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  WHEN SYSTEM$STREAM_HAS_DATA('JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS_STREAM')
AS
  INSERT INTO JOB_MARKET_INTELLIGENCE.RAW.RAW_LOAD_LOG
  SELECT CURRENT_TIMESTAMP(), COUNT(*)
  FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS_STREAM;

-- Child task: runs dbt after the root task finishes
CREATE OR ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.RUN_DBT_BUILD
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  AFTER JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW
AS
  EXECUTE DBT PROJECT JOB_MARKET_INTELLIGENCE.DBT_DEV.JOBMARKET args='build --target dev';

-- Tasks are created suspended. Resume the child first, then the root.
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.RUN_DBT_BUILD RESUME;
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW RESUME;

