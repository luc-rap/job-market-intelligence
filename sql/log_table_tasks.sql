  'LUCIA.RAPANOVA@GMAIL.COM',
  'Snowflake test',
  'If you can read this, email notifications work.'
);

-- 1. Pause the root task while we change the graph
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW SUSPEND;

-- 2. Add a column for the file count (old log rows will just show NULL)
ALTER TABLE JOB_MARKET_INTELLIGENCE.RAW.RAW_LOAD_LOG
  ADD COLUMN FILES_LOADED NUMBER;

-- 3. Root task now records files as well as rows
CREATE OR ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  WHEN SYSTEM$STREAM_HAS_DATA('JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS_STREAM')
AS
  INSERT INTO JOB_MARKET_INTELLIGENCE.RAW.RAW_LOAD_LOG (CHECKED_AT, NEW_ROWS, FILES_LOADED)
  SELECT CURRENT_TIMESTAMP(), COUNT(*), COUNT(DISTINCT SOURCE_FILE)
  FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_ADZUNA_JOBS_STREAM;

-- 4. Email task builds its message from a query
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW SUSPEND;

CREATE OR ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.NOTIFY_DBT_DONE
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  AFTER JOB_MARKET_INTELLIGENCE.DBT_DEV.RUN_DBT_BUILD
AS
EXECUTE IMMEDIATE $$
DECLARE
  files_loaded NUMBER;
  new_rows NUMBER;
  total_rows NUMBER;
  msg VARCHAR;
BEGIN
  SELECT FILES_LOADED, NEW_ROWS
    INTO :files_loaded, :new_rows
    FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_LOAD_LOG
    ORDER BY CHECKED_AT DESC
    LIMIT 1;

  SELECT COUNT(*)
    INTO :total_rows
    FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.INT_ADZUNA_JOBS_DEDUPLICATED;

  msg := 'dbt build for JOBMARKET finished successfully.' || CHR(10) || CHR(10) ||
         'Files loaded: ' || files_loaded || CHR(10) ||
         'New raw rows: ' || new_rows || CHR(10) ||
         'Total rows in INT_ADZUNA_JOBS_DEDUPLICATED: ' || total_rows;

  CALL SYSTEM$SEND_EMAIL('DBT_EMAIL_INT', 'LUCIA.RAPANOVA@GMAIL.COM', 'dbt build finished', :msg);
END;
$$;

-- 5. Resume: children first, root last
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.NOTIFY_DBT_DONE RESUME;
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.RUN_DBT_BUILD RESUME;
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW RESUME;

SELECT name, state, scheduled_from, scheduled_time, query_start_time,
       completed_time, error_message
FROM TABLE(JOB_MARKET_INTELLIGENCE.INFORMATION_SCHEMA.TASK_HISTORY(
  SCHEDULED_TIME_RANGE_START => DATEADD('hour', -3, CURRENT_TIMESTAMP()),
