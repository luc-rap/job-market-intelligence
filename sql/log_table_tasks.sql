  msg VARCHAR;
BEGIN
  SELECT FILES_LOADED, NEW_ROWS
    INTO :files_loaded, :new_rows
    FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_LOAD_LOG
    ORDER BY CHECKED_AT DESC
    LIMIT 1;

  SELECT COUNT(*)
    INTO :total_rows
    FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.INT_ADZUNA_JOBS_DEDUPLICATED;

  msg := 'dbt build for JOBMARKET finished successfully.' || CHR(10) || CHR(10) ||
         'Files loaded: ' || files_loaded || CHR(10) ||
         'New raw rows: ' || new_rows || CHR(10) ||
         'Total rows in INT_ADZUNA_JOBS_DEDUPLICATED: ' || total_rows;

  CALL SYSTEM$SEND_EMAIL('DBT_EMAIL_INT', 'LUCIA.RAPANOVA@GMAIL.COM', 'dbt build finished', :msg);
END;
$$;

-- Finalizer task: finalizer runs after all other tasks in the graph complete or fail to complete
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW SUSPEND;

-- A finalizer can't have the old task's AFTER link, so we replace it
DROP TASK IF EXISTS JOB_MARKET_INTELLIGENCE.DBT_DEV.NOTIFY_DBT_DONE;

CREATE OR ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.NOTIFY_FINALIZER
  WAREHOUSE = SNOWFLAKE_LEARNING_WH
  FINALIZE = JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW
AS
EXECUTE IMMEDIATE $$
DECLARE
  root_id STRING;
  start_time TIMESTAMP_LTZ;
  failed_count NUMBER;
  failed_info VARCHAR;
  files_loaded NUMBER;
  new_rows NUMBER;
  total_rows NUMBER;
  subj VARCHAR;
  msg VARCHAR;
BEGIN
  SELECT SYSTEM$TASK_RUNTIME_INFO('CURRENT_ROOT_TASK_UUID')
    INTO :root_id;

  SELECT SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_ORIGINAL_SCHEDULED_TIMESTAMP')::TIMESTAMP_LTZ
    INTO :start_time;

  -- Did any task in this graph run fail?
  SELECT COUNT(*), LISTAGG(NAME || ': ' || COALESCE(ERROR_MESSAGE, 'no message'), '\n')
    INTO :failed_count, :failed_info
    FROM TABLE(JOB_MARKET_INTELLIGENCE.INFORMATION_SCHEMA.TASK_HISTORY(
      ROOT_TASK_ID => :root_id,
      SCHEDULED_TIME_RANGE_START => :start_time,
      SCHEDULED_TIME_RANGE_END => CURRENT_TIMESTAMP()))
    WHERE STATE = 'FAILED';

  IF (failed_count > 0) THEN
    subj := 'dbt pipeline FAILED';
    msg := 'One or more tasks failed in the JOBMARKET pipeline:' || CHR(10) || CHR(10) || failed_info;
  ELSE
    SELECT FILES_LOADED, NEW_ROWS
      INTO :files_loaded, :new_rows
      FROM JOB_MARKET_INTELLIGENCE.RAW.RAW_LOAD_LOG
      ORDER BY CHECKED_AT DESC
      LIMIT 1;

    SELECT COUNT(*)
      INTO :total_rows
      FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.INT_ADZUNA_JOBS_DEDUPLICATED;

    subj := 'dbt build finished';
    msg := 'dbt build for JOBMARKET finished successfully.' || CHR(10) || CHR(10) ||
           'Files loaded: ' || files_loaded || CHR(10) ||
           'New raw rows: ' || new_rows || CHR(10) ||
           'Total rows in INT_ADZUNA_JOBS_DEDUPLICATED: ' || total_rows;
  END IF;

  CALL SYSTEM$SEND_EMAIL('DBT_EMAIL_INT', 'lucia.rapanova@gmail.com', :subj, :msg);
END;
$$;

-- Resume the finalizer and child, then the root last
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.NOTIFY_FINALIZER RESUME;
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.RUN_DBT_BUILD RESUME;
ALTER TASK JOB_MARKET_INTELLIGENCE.DBT_DEV.CONSUME_NEW_RAW RESUME;

