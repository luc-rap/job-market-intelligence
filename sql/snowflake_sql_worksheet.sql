SELECT
    (SELECT COUNT(*)
     FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.STG_ADZUNA_JOBS)
        AS STAGING_ROWS,

    (SELECT COUNT(*)
     FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.INT_ADZUNA_JOBS_DEDUPLICATED)
        AS DEDUPLICATED_ROWS,

    (SELECT COUNT(DISTINCT JOB_ID)
     FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.STG_ADZUNA_JOBS)
        AS DISTINCT_JOB_IDS;


SELECT
    JOB_ID,
    JOB_TITLE,
    COUNT(*) AS OBSERVATIONS,
    COUNT(DISTINCT SOURCE_FILE) AS SOURCE_FILES,
    MIN(LOADED_AT) AS FIRST_LOADED_AT,
    MAX(LOADED_AT) AS LAST_LOADED_AT,
    LISTAGG(DISTINCT SOURCE_FILE, '\n')
        WITHIN GROUP (ORDER BY SOURCE_FILE) AS FILES
FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.STG_ADZUNA_JOBS
GROUP BY JOB_ID, JOB_TITLE
HAVING COUNT(*) > 1
ORDER BY OBSERVATIONS DESC, LAST_LOADED_AT DESC;

SELECT
    TO_DATE(LOADED_AT) AS INGESTION_DATE,
    COUNT(*) AS OBSERVATIONS,
    COUNT(DISTINCT JOB_ID) AS UNIQUE_JOBS
FROM JOB_MARKET_INTELLIGENCE.DBT_DEV.STG_ADZUNA_JOBS
GROUP BY 1
ORDER BY 1;

